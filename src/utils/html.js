/**
 * Protege un texte avant de l'inserer dans du HTML.
 * A utiliser pour TOUTE valeur venant de l'utilisateur ou de la base.
 * @param {unknown} value
 * @returns {string}
 */
export function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}
